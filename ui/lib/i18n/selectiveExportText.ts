export function selectiveExportText(key: string, variables: Variables = {}): string {
	const suffix = key.includes(".selective.") ? key.split(".selective.")[1] : key;
	const entry = copy[suffix];
	const text = entry?.[getBifrostLanguage() === "zh" ? 1 : 0] ?? key;
	return text.replace(/\{\{(\w+)\}\}/g, (_, name: string) => String(variables[name] ?? ""));
}