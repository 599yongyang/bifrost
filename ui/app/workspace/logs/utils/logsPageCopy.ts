import i18n from "@/lib/i18n";

export function getLogTimestampPattern(date: Date, now = new Date(), language: "en" | "zh" = "en"): string {
	const includeYear = date.getFullYear() !== now.getFullYear();
	if (language === "zh") return includeYear ? "yyyy-MM-dd HH:mm:ss" : "MM-dd HH:mm:ss";
	return includeYear ? "yyyy MMM dd HH:mm:ss" : "MMM dd HH:mm:ss";
}

